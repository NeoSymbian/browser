// numbers, strings, conversions, BigInt, Symbol, Math
assertEq(0.1 + 0.2 === 0.3, false);
assertEq((0.1 + 0.2).toFixed(2), "0.30");
assertEq(Number.MAX_SAFE_INTEGER, 9007199254740991);
assertEq(parseInt("ff", 16), 255);
assertEq(parseFloat("3.25e2"), 325);
assertEq((255).toString(2), "11111111");
assertEq((1e21).toString(), "1e+21");
assertEq(String(-0), "0");
assertEq(Object.is(-0, 0), false);
assertEq(Math.round(2.5), 3);
assertEq(Math.max(), -Infinity);
assertEq(Math.hypot(3, 4), 5);
assertEq(Math.cbrt(27), 3);
assertEq(Math.log2(8), 3);
assertEq(Math.trunc(-4.7), -4);
assertEq(Math.sign(-3), -1);
assertEq(Math.clz32(1), 31);
assertEq(Math.imul(0x7fffffff, 3), 2147483645);
assertEq(2n ** 100n, 1267650600228229401496703205376n);
assertEq((-7n) / 2n, -3n);
assertEq(BigInt.asUintN(8, 257n), 1n);
const s = Symbol("k");
assertEq(typeof s, "symbol");
assertEq(s.description, "k");
assertEq(Symbol.for("x"), Symbol.for("x"));
assertEq("abc".padStart(5, "-"), "--abc");
assertEq("a-b-c".split("-").join("+"), "a+b+c");
assertEq("Straße".toUpperCase(), "STRASSE");
assertEq("ǅ".toLowerCase(), "ǆ");
assertEq("😀".length, 2);
assertEq([..."😀a"].length, 2);
assertEq("x".repeat(3), "xxx");
assertEq("  t ".trim(), "t");
assertEq("abcabc".replaceAll("b", "B"), "aBcaBc");
assertEq(`${1 + 1}`, "2");
assertEq(String.raw`a\n`, "a\\n");
assertEq(Number("0x10"), 16);
assertEq(Number(""), 0);
assertEq(isNaN(Number("x")), true);
assertEq((123.456).toPrecision(4), "123.5");
assertEq((0.000001234).toExponential(2), "1.23e-6");
